bool maybeDispatch(int argc, char **argv, int &exitCode)
{
    std::string algo, url, user, pass, configPath;
    bool haveAlgo = false;

    for (int i = 1; i < argc; ++i) {
        const char *arg = argv[i];
        const char *inlineValue = nullptr;

        if (matchOpt(arg, "-a", "--algo", inlineValue)) {
            haveAlgo = true;
            algo = inlineValue ? inlineValue : ((i + 1 < argc) ? argv[++i] : "");
        }
        else if (matchOpt(arg, "-o", "--url", inlineValue)) {
            url = inlineValue ? inlineValue : ((i + 1 < argc) ? argv[++i] : "");
        }
        else if (matchOpt(arg, "-u", "--user", inlineValue)) {
            user = inlineValue ? inlineValue : ((i + 1 < argc) ? argv[++i] : "");
        }
        else if (matchOpt(arg, "-p", "--pass", inlineValue)) {
            pass = inlineValue ? inlineValue : ((i + 1 < argc) ? argv[++i] : "");
        }
        else if (matchOpt(arg, "-c", "--config", inlineValue)) {
            configPath = inlineValue ? inlineValue : ((i + 1 < argc) ? argv[++i] : "");
        }
    }

    // config.json fallback: only consulted for fields the command line did not already set, same precedence
    // as poolpayminer's normal config (CLI overrides the file). Only pools[0] is looked at: this wrapper is for
    // the simple, single-pool case that "-a ric -o ... -u ... -p ..." itself covers.
    if (!configPath.empty() && (url.empty() || user.empty() || !haveAlgo)) {
        rapidjson::Document doc;
        if (Json::get(configPath.c_str(), doc) && doc.IsObject()) {
            const auto poolsIt = doc.FindMember("pools");
            if (poolsIt != doc.MemberEnd() && poolsIt->value.IsArray() && !poolsIt->value.Empty()) {
                const auto &pool = poolsIt->value[0];
                if (!haveAlgo) {
                    if (const char *a = Json::getString(pool, "algo")) { algo = a; haveAlgo = true; }
                }
                if (url.empty()) {
                    if (const char *u = Json::getString(pool, "url")) url = u;
                }
                if (user.empty()) {
                    if (const char *u = Json::getString(pool, "user")) user = u;
                }
                if (pass.empty()) {
                    if (const char *p = Json::getString(pool, "pass")) pass = p;
                }
            }
        }
    }

    if (!haveAlgo || !isRiecoinAlgo(algo)) {
        return false;
    }

    printf("poolpayminer: algorithm \"%s\" is Riecoin's prime constellation search, not RandomX: handing off to the bundled rieMiner.\n", algo.c_str());

    if (url.empty()) {
        fprintf(stderr, "poolpayminer: -o/--url (pool host:port) is required for Riecoin.\n");
        exitCode = 1;
        return true;
    }

    std::string host, port;
    splitHostPort(url, host, port);

    const std::string dir = exeDir();
#   ifdef _WIN32
    const std::string rieMinerPath = dir + "rieMiner.exe";
#   else
    const std::string rieMinerPath = dir + "rieMiner";
#   endif
    const std::string confPath = dir + "poolpayminer-ric.conf";

    std::ifstream check(rieMinerPath, std::ios::binary);
    if (!check.good()) {
        fprintf(stderr, "poolpayminer: rieMiner was not found next to this program (expected %s). Redownload the poolpayminer package: it ships rieMiner alongside it for Riecoin.\n", rieMinerPath.c_str());
        exitCode = 1;
        return true;
    }
    check.close();

    if (!writeRieMinerConf(confPath, host, port, user, pass)) {
        fprintf(stderr, "poolpayminer: could not write %s\n", confPath.c_str());
        exitCode = 1;
        return true;
    }

    std::string cmd = "\"" + rieMinerPath + "\" \"" + confPath + "\"";
#   ifdef _WIN32
    cmd = "\"" + cmd + "\""; // cmd.exe quirk: a quoted first token needs the whole command re-quoted once more
#   endif

    exitCode = std::system(cmd.c_str());
#   ifndef _WIN32
    if (exitCode != -1) {
        exitCode = WIFEXITED(exitCode) ? WEXITSTATUS(exitCode) : 1;
    }
#   endif

    return true;
}


