bool isRiecoinAlgo(const std::string &algo)
{
    std::string a;
    a.reserve(algo.size());
    for (char c : algo) a.push_back(static_cast<char>(::tolower(static_cast<unsigned char>(c))));

    return a == "ric" || a == "riecoin" || a == "riecoin/ric";
}


// argv[i] == flag (e.g. "-a"): value is argv[i + 1]. argv[i] == "--long=value" or "--long": value follows the same way.
bool matchOpt(const char *arg, const char *shortFlag, const char *longFlag, const char *&inlineValue)
{
    inlineValue = nullptr;

    if (shortFlag && strcmp(arg, shortFlag) == 0) {
        return true;
    }

    if (longFlag) {
        const size_t len = strlen(longFlag);
        if (strncmp(arg, longFlag, len) == 0) {
            if (arg[len] == '\0') {
                return true;
            }

            if (arg[len] == '=') {
                inlineValue = arg + len + 1;
                return true;
            }
        }
    }

    return false;
}


// The exe's own directory, with a trailing separator, so rieMiner is found next to poolpayminer regardless of
// the working directory the user launched it from.
std::string exeDir()
{
    char path[4096] = {};

#   ifdef _WIN32
    const DWORD n = GetModuleFileNameA(nullptr, path, sizeof(path));
    if (n == 0 || n >= sizeof(path)) {
        return {};
    }
    const char sep = '\\';
#   else
    const ssize_t n = readlink("/proc/self/exe", path, sizeof(path) - 1);
    if (n <= 0) {
        return {};
    }
    path[n] = '\0';
    const char sep = '/';
#   endif

    std::string s(path);
    const size_t pos = s.find_last_of(sep);
    if (pos == std::string::npos) {
        return {};
    }

    return s.substr(0, pos + 1);
}


void splitHostPort(std::string url, std::string &host, std::string &port)
{
    // strip a scheme prefix if someone pasted a URL with one; poolpayminer's own -o never has one, but be forgiving
    const size_t scheme = url.find("://");
    if (scheme != std::string::npos) {
        url = url.substr(scheme + 3);
    }

    const size_t colon = url.find_last_of(':');
    if (colon == std::string::npos) {
        host = url;
        port.clear();
        return;
    }

    host = url.substr(0, colon);
    port = url.substr(colon + 1);
}


bool writeRieMinerConf(const std::string &path, const std::string &host, const std::string &port, const std::string &user, const std::string &pass)
{
    std::ofstream f(path, std::ios::out | std::ios::trunc);
    if (!f) {
        return false;
    }

    f << "# generated by poolpayminer, do not edit: it is overwritten on every start\n"
      << "Mode = Pool\n"
      << "Host = " << host << "\n"
      << "Port = " << (port.empty() ? "28338" : port) << "\n"
      << "Username = " << user << "\n"
      << "Password = " << (pass.empty() ? "x" : pass) << "\n";

    return f.good();
}


